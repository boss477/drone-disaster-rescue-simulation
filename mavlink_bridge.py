"""MAVLink telemetry bridge for the flood-rescue SIMULATION.

    SIMULATION ONLY. No real drone, motor or flight controller is connected.

    3D simulation (browser)  ->  this bridge  ->  UDP MAVLink  ->  QGroundControl

By default the bridge is *send-only telemetry*: it announces a virtual vehicle
(system id 42) and streams simulated position, altitude, battery, mission
progress, people detected and package delivery status to QGroundControl's UDP
port. It never reads or acts on incoming commands.

Flight commands (arm / take off / land) can only be sent to a PX4 or ArduPilot
*SITL* instance, and only when ALL of these hold:
  * "mode" is "sitl" in mavlink_config.json,
  * "sitl.enabled" is true in mavlink_config.json,
  * --enable-sitl-commands is passed on the command line,
  * the SITL endpoint is on this computer (loopback address).

    py mavlink_bridge.py                       # telemetry only (default)
    py mavlink_bridge.py --dry-run             # print telemetry, open no sockets
    py mavlink_bridge.py --standalone          # ignore the browser, run the built-in mission
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Optional

import mission_model

PROJECT_DIR = Path(__file__).resolve().parent
DEFAULT_CONFIG = PROJECT_DIR / "mavlink_config.json"
LOOPBACK_HOSTS = {"127.0.0.1", "localhost", "::1"}
METRES_PER_DEGREE = 111_320.0

# MAVLink constants (literal values so this module and its tests need no pymavlink)
MAV_TYPE_QUADROTOR = 2
MAV_AUTOPILOT_GENERIC = 0
MAV_MODE_FLAG_CUSTOM_MODE_ENABLED = 1  # note: SAFETY_ARMED is deliberately NOT set
MAV_STATE_STANDBY = 3
MAV_STATE_ACTIVE = 4
GPS_FIX_TYPE_3D_FIX = 3
MAV_SEVERITY_INFO = 6
MAV_SEVERITY_WARNING = 4

BANNER = (
    "=" * 64 + "\n"
    "  SIMULATION ONLY - no real drone, motor or flight controller.\n"
    "  Telemetry is generated by the 3D simulation, not by hardware.\n"
    + "=" * 64
)


class SafetyError(RuntimeError):
    """Raised when something would send flight commands without explicit SITL opt-in."""


# ------------------------------------------------------------------ config ---

def load_config(path: Path = DEFAULT_CONFIG) -> dict[str, Any]:
    with Path(path).open(encoding="utf-8") as handle:
        return json.load(handle)


def validate_config(cfg: dict[str, Any]) -> None:
    if cfg.get("mode", "telemetry") not in ("telemetry", "sitl"):
        raise ValueError('"mode" must be "telemetry" or "sitl"')
    port = cfg["qgc"]["udp_port"]
    if not isinstance(port, int) or not 1 <= port <= 65535:
        raise ValueError("qgc.udp_port must be an integer from 1 to 65535")
    if not 0 < float(cfg.get("update_rate_hz", 4)) <= 50:
        raise ValueError("update_rate_hz must be between 0 and 50")


def endpoint_host(endpoint: str) -> str:
    """Host part of a pymavlink endpoint such as ``udpout:127.0.0.1:14540``."""
    parts = endpoint.split(":")
    return parts[1] if len(parts) >= 3 else ""


def commands_allowed(cfg: dict[str, Any], cli_flag: bool) -> bool:
    """True only when every SITL safety condition is met (see module docstring)."""
    sitl = cfg.get("sitl", {})
    return bool(
        cli_flag
        and cfg.get("mode") == "sitl"
        and sitl.get("enabled") is True
        and endpoint_host(str(sitl.get("endpoint", ""))) in LOOPBACK_HOSTS
    )


# ------------------------------------------------------------- conversions ---

def sim_to_geo(home: dict[str, float], x: float, z: float) -> tuple[float, float]:
    """Scene metres (+x east, -z north) to latitude/longitude degrees."""
    north, east = -z, x
    lat0 = home["latitude_deg"]
    lat = lat0 + north / METRES_PER_DEGREE
    lon = home["longitude_deg"] + east / (METRES_PER_DEGREE * math.cos(math.radians(lat0)))
    return lat, lon


def telemetry_values(cfg: dict[str, Any], state: dict[str, Any], mission: dict[str, Any]) -> dict[str, Any]:
    """Convert a simulation state into MAVLink-unit values."""
    home = cfg["home"]
    pos, vel = state["position"], state["velocity"]
    pad_height = mission["base"]["pad_height"]
    lat, lon = sim_to_geo(home, pos["x"], pos["z"])
    rel_alt_m = max(pos["y"] - pad_height, 0.0)
    pct = max(0.0, min(100.0, float(state["battery_percent"])))
    cell_mv = int(3300 + 900 * pct / 100)  # 4S pack, 3.3-4.2 V per cell
    vn, ve = -vel["z"], vel["x"]  # north / east
    return {
        "lat_e7": int(round(lat * 1e7)),
        "lon_e7": int(round(lon * 1e7)),
        "alt_mm": int(round((home["altitude_msl_m"] + rel_alt_m) * 1000)),
        "rel_alt_mm": int(round(rel_alt_m * 1000)),
        "vn_cms": int(round(vn * 100)),
        "ve_cms": int(round(ve * 100)),
        "vd_cms": int(round(-vel["y"] * 100)),
        "ground_speed": math.hypot(vn, ve),
        "climb": vel["y"],
        "heading_deg": float(state["heading_deg"]) % 360.0,
        "battery_pct": int(round(pct)),
        "cell_mv": cell_mv,
        "pack_mv": cell_mv * 4,
        "mission_seq": int(state["mission_seq"]),
        "mission_total": int(state["mission_total"]),
        "people_detected": int(state["people_detected"]),
        "packages_delivered": int(state["packages_delivered"]),
        "packages_onboard": int(state["packages_onboard"]),
        "progress_percent": int(round(state["progress_percent"])),
        "phase": str(state["phase"]),
        "in_flight": state["phase"] not in ("loading", "complete"),
    }


def _name(text: str) -> bytes:
    return text.encode("ascii")[:10].ljust(10, b"\0")


def build_messages(
    cfg: dict[str, Any], state: dict[str, Any], mission: dict[str, Any], boot_ms: int, previous: Optional[dict[str, Any]] = None
) -> list[tuple[str, tuple]]:
    """Messages for one update as ``(name, args)``; ``name`` maps to ``mav.<name>_send``.

    ``previous`` is the last state sent; it is used to emit event messages
    (mission item reached, phase changes, deliveries) exactly once.
    """
    v = telemetry_values(cfg, state, mission)
    status = MAV_STATE_ACTIVE if v["in_flight"] else MAV_STATE_STANDBY
    yaw = math.radians(v["heading_deg"])
    if yaw > math.pi:
        yaw -= 2 * math.pi
    messages: list[tuple[str, tuple]] = [
        ("heartbeat", (MAV_TYPE_QUADROTOR, MAV_AUTOPILOT_GENERIC, MAV_MODE_FLAG_CUSTOM_MODE_ENABLED, 0, status)),
        ("sys_status", (0, 0, 0, 0, v["pack_mv"], -1, v["battery_pct"], 0, 0, 0, 0, 0, 0)),
        ("battery_status", (0, 1, 1, 32767, [v["cell_mv"]] * 4 + [65535] * 6, -1, -1, -1, v["battery_pct"])),
        ("gps_raw_int", (boot_ms * 1000, GPS_FIX_TYPE_3D_FIX, v["lat_e7"], v["lon_e7"], v["alt_mm"], 100, 150,
                         int(v["ground_speed"] * 100), int(v["heading_deg"] * 100), 12)),
        ("global_position_int", (boot_ms, v["lat_e7"], v["lon_e7"], v["alt_mm"], v["rel_alt_mm"],
                                 v["vn_cms"], v["ve_cms"], v["vd_cms"], int(v["heading_deg"] * 100))),
        ("attitude", (boot_ms, 0.0, 0.0, yaw, 0.0, 0.0, 0.0)),
        ("vfr_hud", (v["ground_speed"], v["ground_speed"], int(v["heading_deg"]), 0, v["rel_alt_mm"] / 1000.0, v["climb"])),
        ("mission_current", (v["mission_seq"], v["mission_total"])),
        ("named_value_int", (boot_ms, _name("PEOPLE"), v["people_detected"])),
        ("named_value_int", (boot_ms, _name("DELIVERED"), v["packages_delivered"])),
        ("named_value_int", (boot_ms, _name("ONBOARD"), v["packages_onboard"])),
        ("named_value_int", (boot_ms, _name("PROGRESS"), v["progress_percent"])),
    ]
    prev = telemetry_values(cfg, previous, mission) if previous else None
    if prev is None or prev["phase"] != v["phase"]:
        text = f"[SIM] phase: {v['phase']} (simulated, no real vehicle)"
        messages.append(("statustext", (MAV_SEVERITY_INFO, text.encode("ascii"))))
    if prev is not None and v["packages_delivered"] > prev["packages_delivered"]:
        text = f"[SIM] simulated package {v['packages_delivered']} delivered"
        messages.append(("statustext", (MAV_SEVERITY_INFO, text.encode("ascii"))))
    if prev is not None and v["people_detected"] > prev["people_detected"]:
        text = f"[SIM] simulated people detected: {v['people_detected']}"
        messages.append(("statustext", (MAV_SEVERITY_INFO, text.encode("ascii"))))
    if prev is not None and v["mission_seq"] > prev["mission_seq"]:
        messages.append(("mission_item_reached", (prev["mission_seq"],)))
    return messages


# ------------------------------------------------------------------ sources ---

class StateSource:
    """Reads state from the 3D page via the local server, else runs the built-in mission."""

    def __init__(self, cfg: dict[str, Any], mission: dict[str, Any], standalone: bool = False):
        self.url = cfg["sim_server_url"]
        self.mission = mission
        self.timeline = mission_model.build_timeline(mission)
        self.allow_fallback = standalone or cfg.get("use_builtin_mission_when_page_closed", True)
        self.force_standalone = standalone
        self._standalone_start: Optional[float] = None
        self.last_origin = ""

    def _from_page(self) -> Optional[dict[str, Any]]:
        try:
            with urllib.request.urlopen(self.url, timeout=0.5) as response:
                payload = json.load(response)
        except (urllib.error.URLError, OSError, ValueError):
            return None
        return payload["state"] if payload.get("connected") else None

    def get(self) -> Optional[dict[str, Any]]:
        if not self.force_standalone:
            state = self._from_page()
            if state is not None:
                self.last_origin, self._standalone_start = "3D simulation page", None
                return state
        if not self.allow_fallback:
            self.last_origin = ""
            return None
        if self._standalone_start is None:
            self._standalone_start = time.monotonic()
        self.last_origin = "built-in mission model"
        return mission_model.state_at(self.mission, self.timeline, time.monotonic() - self._standalone_start)


# ------------------------------------------------------------------- output ---

def emit(connection: Any, messages: list[tuple[str, tuple]]) -> None:
    for name, args in messages:
        sender = getattr(connection.mav, f"{name}_send")
        try:
            sender(*args)
        except TypeError:  # older/newer pymavlink dialects with different arity
            if name == "mission_current":
                sender(args[0])
            else:
                raise


class SitlController:
    """Optional arm/takeoff/land commands for a local PX4/ArduPilot SITL (never real hardware)."""

    def __init__(self, cfg: dict[str, Any], cli_flag: bool):
        if not commands_allowed(cfg, cli_flag):
            raise SafetyError(
                "Flight commands are disabled. They need mode=sitl, sitl.enabled=true, "
                "--enable-sitl-commands and a loopback endpoint."
            )
        from pymavlink import mavutil

        self.mavutil = mavutil
        self.cfg = cfg["sitl"]
        self.conn = mavutil.mavlink_connection(self.cfg["endpoint"], source_system=255, source_component=190)
        beat = self.conn.wait_heartbeat(timeout=10)
        if beat is None:
            raise SafetyError("No heartbeat from SITL within 10 s - is the simulator running?")
        self.autopilot = beat.autopilot
        self.target = (self.conn.target_system, self.conn.target_component)

    def _command(self, command: int, *params: float) -> None:
        padded = list(params) + [0.0] * (7 - len(params))
        self.conn.mav.command_long_send(*self.target, command, 0, *padded)

    def arm_and_takeoff(self) -> None:
        mav = self.mavutil.mavlink
        if self.autopilot == mav.MAV_AUTOPILOT_ARDUPILOTMEGA:
            self.conn.set_mode("GUIDED")
        self._command(mav.MAV_CMD_COMPONENT_ARM_DISARM, 1)
        time.sleep(1.0)
        self._command(mav.MAV_CMD_NAV_TAKEOFF, 0, 0, 0, 0, 0, 0, float(self.cfg.get("takeoff_altitude_m", 9)))

    def land(self) -> None:
        self._command(self.mavutil.mavlink.MAV_CMD_NAV_LAND)


# --------------------------------------------------------------------- main ---

def parse_args(argv: Optional[list[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="MAVLink telemetry bridge (SIMULATION ONLY)")
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--standalone", action="store_true", help="Ignore the browser; run the built-in mission model")
    parser.add_argument("--dry-run", action="store_true", help="Print telemetry; open no network connection")
    parser.add_argument("--duration", type=float, help="Stop after this many seconds (default: run until Ctrl+C)")
    parser.add_argument("--enable-sitl-commands", action="store_true",
                        help="Allow arm/takeoff/land commands to a LOCAL SITL (also needs mode=sitl and sitl.enabled)")
    return parser.parse_args(argv)


def main(argv: Optional[list[str]] = None) -> int:
    args = parse_args(argv)
    sys.stdout.reconfigure(line_buffering=True)
    print(BANNER)
    cfg = load_config(args.config)
    validate_config(cfg)
    mission = mission_model.load_mission()

    sitl: Optional[SitlController] = None
    if args.enable_sitl_commands or cfg.get("mode") == "sitl":
        if args.dry_run:
            print("--dry-run: SITL commands are never sent.")
        else:
            try:
                sitl = SitlController(cfg, args.enable_sitl_commands)
            except (SafetyError, ImportError, OSError) as exc:
                print(f"SITL commands NOT enabled: {exc}", file=sys.stderr)
                return 1
            print("SITL command mode ENABLED for the local simulator at", cfg["sitl"]["endpoint"])
    else:
        print("Telemetry-only mode: no flight commands will be sent.")

    connection = None
    if not args.dry_run:
        try:
            from pymavlink import mavutil
        except ImportError:
            print("pymavlink is not installed. Run ./setup.ps1 -Mavlink or "
                  "py -m pip install -r requirements-mavlink.txt (or use --dry-run).", file=sys.stderr)
            return 1
        target = f"udpout:{cfg['qgc']['host']}:{cfg['qgc']['udp_port']}"
        connection = mavutil.mavlink_connection(
            target, source_system=cfg["system_id"], source_component=cfg.get("component_id", 1)
        )
        print(f"Sending simulated telemetry to QGroundControl at {target} (system id {cfg['system_id']})")
    source = StateSource(cfg, mission, standalone=args.standalone)
    period = 1.0 / float(cfg.get("update_rate_hz", 4))
    started = time.monotonic()
    previous: Optional[dict[str, Any]] = None
    origin = None
    try:
        while args.duration is None or time.monotonic() - started < args.duration:
            tick = time.monotonic()
            state = source.get()
            if state is None:
                if origin != "":
                    print("Waiting for the 3D simulation page (start it with ./run_rescue_simulation.ps1)...")
                    origin = ""
            else:
                if source.last_origin != origin:
                    origin = source.last_origin
                    print(f"State source: {origin}")
                messages = build_messages(cfg, state, mission, int((tick - started) * 1000), previous)
                if args.dry_run:
                    values = telemetry_values(cfg, state, mission)
                    print(json.dumps({k: values[k] for k in (
                        "phase", "lat_e7", "lon_e7", "rel_alt_mm", "battery_pct", "people_detected", "packages_delivered")}))
                else:
                    emit(connection, messages)
                if sitl and previous is not None and state["phase"] != previous["phase"]:
                    if state["phase"] == "takeoff":
                        sitl.arm_and_takeoff()
                    elif state["phase"] == "landing":
                        sitl.land()
                previous = state
            time.sleep(max(period - (time.monotonic() - tick), 0.0))
    except KeyboardInterrupt:
        print("\nStopped.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
